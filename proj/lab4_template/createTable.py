# 2. 初始化一個字典來儲存每種運算的總週期
op_cycles = {}
total_inference_cycles = 0

# 3. 用來解析總週期的正規表示式
total_cycles_regex = re.compile(r".*\( *(\d+) *\).*cycles total")

# 4. 逐行讀取數據
data_io = io.StringIO(data)
for line in data_io.readlines():
    line = line.strip()

    # 嘗試解析 "op,cycle" 格式
    parts = line.split(',')
    if len(parts) == 3:
        try:
            op_name = parts[1]
            cycles = int(parts[2])
            
            # 累加 cycle
            if op_name in op_cycles:
                op_cycles[op_name] += cycles
            else:
                op_cycles[op_name] = cycles
        except ValueError:
            pass 

    # 嘗試解析 "total cycles" 格式
    match = total_cycles_regex.match(line)
    if match:
        total_inference_cycles = int(match.group(1))

# 5. 計算 "純運算總和" (Sum of all operation ticks)
sum_of_all_op_ticks = sum(op_cycles.values())

if sum_of_all_op_ticks == 0:
    print("錯誤：沒有偵測到任何運算 (operation) 數據。")
else:
    print(f"總推論週期 (Total Inference Cycles): {total_inference_cycles:,} (包含框架開銷)")
    print(f"純運算總週期 (Sum of Op Ticks):   {sum_of_all_op_ticks:,} (將以此為 100% 基準)\n")

    # 6. 將字典轉換為 Pandas DataFrame
    df = pd.DataFrame(list(op_cycles.items()), columns=['Operation', 'Cycles'])
    
    # 7. 計算百分比 (*** 這裡保持為 float ***)
    df['Percentage'] = (df['Cycles'] / sum_of_all_op_ticks) * 100
    
    # 8. 依照百分比排序
    df = df.sort_values(by='Percentage', ascending=False)
    
    # --- 9. (新) 為了圓餅圖可讀性，將小於 2% 的項目分組 ---
    #    (*** 現在 Percentage 還是 float，所以比較可以正常運作 ***)
    threshold = 2.0
    df_plot = df[df['Percentage'] >= threshold].copy()
    
    # 計算 'others' 的百分比總和
    others_percentage = df[df['Percentage'] < threshold]['Percentage'].sum()
    
    # 如果 'others' 有值，就新增一個 row
    if others_percentage > 0:
        others_row = pd.DataFrame([{'Operation': 'others', 'Cycles': 0, 'Percentage': others_percentage}])
        df_plot = pd.concat([df_plot, others_row], ignore_index=True)

    # --- 10. (新) 印出格式化的表格 ---
    print("--- 運算時間佔比 (Operation Time Proportions) ---")
    
    # 建立一個 *新的* df_print 來做格式化，才不會汙染到 df
    df_print = df.copy() 
    
    # (*** 格式化字串的步驟移到這裡 ***)
    df_print['Percentage'] = df_print['Percentage'].map('{:,.2f}%'.format)
    df_print['Cycles'] = df_print['Cycles'].map('{:,}'.format) # 加上千分位
    print(df_print.to_string(index=False))

    # --- 11. (新) 繪製並儲存圓餅圖 ---
    #     (*** 這裡使用的是 df_plot['Percentage']，它仍然是 float ***)
    plt.figure(figsize=(10, 8)) 
    
    explode = [0.01] * len(df_plot) 
    
    patches, texts, autotexts = plt.pie(
        df_plot['Percentage'],
        labels=df_plot['Operation'],
        autopct='%1.1f%%',       
        startangle=140,          
        pctdistance=0.85,        
        labeldistance=1.1,       
        explode=explode
    )
    
    for text in texts:
        text.set_fontsize(12)
    for autotext in autotexts:
        autotext.set_fontsize(10)

    plt.title('Operation Time Proportions', fontsize=16) 
    plt.axis('equal') 
    
    # 儲存圖片
    plot_filename = 'operation_pie_chart.png'
    plt.savefig(plot_filename, bbox_inches='tight') 
    
    print(f"\n圓餅圖已儲存為 '{plot_filename}'")